// Generate the official OpenUI prompt and schema used by the Host validator.
import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { openuiChatLibrary, openuiChatPromptOptions } from '@openuidev/react-ui/genui-lib'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src/generated')
mkdirSync(outDir, { recursive: true })

const options = {
  ...openuiChatPromptOptions,
  additionalRules: [
    ...openuiChatPromptOptions.additionalRules.filter(rule => !rule.startsWith('When asked about data, generate realistic/plausible data')),
    'Write all visible text in the language of the user question.',
    'Do not invent precise external facts, citations, source URLs, or numbers. Use only facts supplied by the user or available in the conversation.',
  ],
}
const systemPrompt = openuiChatLibrary.prompt(options)
const librarySchema = openuiChatLibrary.toJSONSchema()
const componentNames = Object.keys(librarySchema.$defs ?? {})

if (!systemPrompt || !librarySchema || componentNames.length < 50) throw new Error('official OpenUI library is missing')

const source = `// Generated by scripts/gen.mjs from @openuidev/react-ui. Do not edit by hand.
export const COMPONENT_NAMES = ${JSON.stringify(componentNames)}
export const LIBRARY_SCHEMA = ${JSON.stringify(librarySchema)}
export const SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)}
`
writeFileSync(join(outDir, 'library.js'), source)
console.log(`generated src/generated/library.js — ${componentNames.length} official components`)
